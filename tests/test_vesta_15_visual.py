#!/usr/bin/env python3
"""Synthetic unit tests for V15 evidence plumbing; NOT genuine VESTA captures."""
from __future__ import annotations

from copy import deepcopy
import hashlib
import json
from pathlib import Path
import sys
import tempfile
import unittest

sys.path.insert(0, str(Path(__file__).resolve().parent / "validation"))
import vesta_15_visual as visual


class VisualEvidenceTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix="v15-synthetic-test-")
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.out = self.root / "reports"
        self.cases = visual.pinned_cases()
        self.case = deepcopy(self.cases[0])
        self.case["settings"]["outputPixels"] = [24, 16]
        self.image = self.root / "left.png"
        self.right = self.root / "right.png"
        self.picture(self.image)
        self.picture(self.right)

    def picture(self, path: Path, shift: int = 0):
        w, h = 24, 16
        pixels = bytearray([255] * (w * h * 3))
        for y in range(3, 11):
            for x in range(4 + shift, 12 + shift):
                offset = (y * w + x) * 3
                pixels[offset:offset + 3] = bytes((28, 120, 175))
        visual.png_write(path, w, h, bytes(pixels))

    def evidence(self):
        raw = {
            "vestaGuiExecuted": True,
            "vestaVersion": "3.5.8",
            "operator": "synthetic unit test (NOT a real GUI measurement)",
            "platform": "synthetic local-only unit test",
            "kristalyapiCommit": "f" * 40,
            "cases": [{
                "id": self.case["id"],
                "sourceSha256": self.case["sourceSha256"],
                "settings": self.case["settings"],
                "vesta": {
                    "path": "left.png", "sha256": visual.digest(self.image.read_bytes()),
                    "roi": [0, 0, 24, 16], "captureMethod": "Synthetic PNG generated by unit test",
                    "captureDate": "2026-10-30"
                },
                "kristalyapi": {
                    "path": "right.png", "sha256": visual.digest(self.right.read_bytes()),
                    "roi": [0, 0, 24, 16], "captureMethod": "Synthetic PNG generated by unit test",
                    "captureDate": "2026-10-30"
                }
            }]
        }
        path = self.root / "fake-evidence.json"
        path.write_text(json.dumps(raw), encoding="utf-8")
        return path

    def test_manifest_pins_real_repository_source_bytes(self):
        self.assertEqual(len(self.cases), 5)
        self.assertEqual(len(set(c["id"] for c in self.cases)), 5)
        for case in self.cases:
            source = visual.ROOT / case["source"]
            self.assertEqual(visual.git_blob(source.read_bytes()), case["sourceGitBlobSha1"])
            self.assertEqual(len(case["sourceSha256"]), 64)

    def test_default_report_cannot_claim_gui_or_scientific_parity(self):
        result = visual.run(self.cases, None, self.out)
        self.assertEqual(result["vestaGuiStatus"], "NOT_RUN")
        self.assertEqual(result["capturedCases"], 0)
        self.assertFalse(result["evidenceComplete"])
        self.assertTrue(all(r["visualMetrics"] is None for r in result["cases"]))
        self.assertTrue(all(r["scientificParity"] == "NOT_ESTABLISHED" for r in result["cases"]))
        self.assertEqual(len((self.out / "metrics.csv").read_text().splitlines()), 6)
        with self.assertRaisesRegex(ValueError, "Missing actual screenshot evidence"):
            visual.run(self.cases, None, self.out, require_all=True)

    def test_rgb_png_roundtrip_and_identical_metrics(self):
        decoded = visual.png_rgb(self.image, (255, 255, 255))
        self.assertEqual(decoded[:2], (24, 16))
        left = visual.crop(decoded, [0, 0, 24, 16])
        data, combined = visual.metrics(left, left, (255, 255, 255))
        self.assertEqual(data["foregroundIoU"], 1)
        self.assertEqual(data["meanAbsoluteRGBDifference255"], 0)
        self.assertEqual(data["bboxCenterShiftPx"], [0, 0])
        output = self.root / "comparison.png"
        visual.png_write(output, 72, 16, combined)
        self.assertEqual(visual.png_rgb(output, (255, 255, 255))[:2], (72, 16))

    def test_shape_difference_is_measured_but_never_called_parity(self):
        self.picture(self.right, shift=2)
        evidence = self.evidence()
        result = visual.run([self.case], evidence, self.out, require_all=True)
        self.assertTrue(result["evidenceComplete"])
        self.assertEqual(result["capturedCases"], 1)
        record = result["cases"][0]
        self.assertLess(record["visualMetrics"]["foregroundIoU"], 1)
        self.assertGreater(record["visualMetrics"]["meanAbsoluteRGBDifference255"], 0)
        self.assertEqual(record["visualMetrics"]["bboxCenterShiftPx"], [2, 0])
        self.assertEqual(result["scientificParity"], "NOT_ESTABLISHED")
        self.assertIn("HUMAN_REVIEW_REQUIRED", record["vestaGuiStatus"])
        self.assertTrue((self.out / record["comparisonPng"]).is_file())
        self.assertEqual(visual.png_rgb(self.out / record["comparisonPng"], (255, 255, 255))[:2],
                         (72, 16))

    def test_hash_and_source_substitution_are_rejected(self):
        evidence = self.evidence()
        payload = json.loads(evidence.read_text())
        payload["cases"][0]["vesta"]["sha256"] = "0" * 64
        evidence.write_text(json.dumps(payload))
        with self.assertRaisesRegex(ValueError, "SHA-256"):
            visual.run([self.case], evidence, self.out)
        payload["cases"][0]["vesta"]["sha256"] = visual.digest(self.image.read_bytes())
        payload["cases"][0]["sourceSha256"] = "0" * 64
        evidence.write_text(json.dumps(payload))
        with self.assertRaisesRegex(ValueError, "Unmatched source"):
            visual.run([self.case], evidence, self.out)

    def test_wrong_camera_settings_and_version_fail_closed(self):
        evidence = self.evidence()
        payload = json.loads(evidence.read_text())
        payload["cases"][0]["settings"]["viewDirection"] = "[111]"
        evidence.write_text(json.dumps(payload))
        with self.assertRaisesRegex(ValueError, "settings"):
            visual.run([self.case], evidence, self.out)
        payload["cases"][0]["settings"] = self.case["settings"]
        payload["vestaVersion"] = "3.90.9a"
        evidence.write_text(json.dumps(payload))
        with self.assertRaisesRegex(ValueError, "version"):
            visual.run([self.case], evidence, self.out)

    def test_missing_gui_declaration_and_path_escape_fail_closed(self):
        evidence = self.evidence()
        payload = json.loads(evidence.read_text())
        payload["vestaGuiExecuted"] = False
        evidence.write_text(json.dumps(payload))
        with self.assertRaisesRegex(ValueError, "execution"):
            visual.run([self.case], evidence, self.out)
        payload["vestaGuiExecuted"] = True
        payload["cases"][0]["vesta"]["path"] = "../not-a-png.png"
        evidence.write_text(json.dumps(payload))
        with self.assertRaisesRegex(ValueError, "outside"):
            visual.run([self.case], evidence, self.out)

    def test_image_crc_and_roi_rejected(self):
        evidence = self.evidence()
        with self.assertRaisesRegex(ValueError, "ROI"):
            visual.crop(visual.png_rgb(self.image, (255, 255, 255)), [0, 0, 50, 50])
        payload = bytearray(self.image.read_bytes())
        payload[32] ^= 1
        self.image.write_bytes(payload)
        with self.assertRaisesRegex(ValueError, "CRC"):
            visual.png_rgb(self.image, (255, 255, 255))
        with self.assertRaisesRegex(ValueError, "SHA-256"):
            visual.run([self.case], evidence, self.out)

    def test_roi_mismatch_and_bad_capture_date_fail_closed(self):
        evidence = self.evidence()
        payload = json.loads(evidence.read_text())
        payload["cases"][0]["kristalyapi"]["roi"] = [1, 0, 23, 16]
        evidence.write_text(json.dumps(payload))
        with self.assertRaisesRegex(ValueError, "identical ROI"):
            visual.run([self.case], evidence, self.out)
        payload["cases"][0]["kristalyapi"]["roi"] = [0, 0, 24, 16]
        payload["cases"][0]["vesta"]["captureDate"] = "2026-02-30"
        evidence.write_text(json.dumps(payload))
        with self.assertRaisesRegex(ValueError, "calendar"):
            visual.run([self.case], evidence, self.out)

    def test_p14_source_pins_link_only_user_supplied_audit_metadata(self):
        p14 = self.root / "p14-synthetic.json"
        document = {
            "protocol": "package14-vesta3-manual-equations-real-cif",
            "manualScientificGate": "PASS",
            "vestaGuiExecuted": True,
            "vestaGuiStatus": "captured-human-evidence",
            "vestaGuiEvidenceAudit": {
                "version": "3.5.8",
                "cases": [{
                    "id": "cod-nacl-Na1", "capturedFromGui": True,
                    "screenshotSha256": "a"*64, "consoleTextSha256": "b"*64,
                    "maxDistanceErrorA": .01,
                }],
            },
            "cases": [{"id": "cod-nacl-Na1", "source": "cod1000041",
                       "vestaGuiStatus": "captured-human-evidence"}]
        }
        p14.write_text(json.dumps(document))
        linked = visual.link_p14_report(p14, self.cases)
        self.assertIn("HUMAN_REVIEW_REQUIRED", linked["status"])
        self.assertEqual(linked["linkedMeasurements"][0]["v15Scene"], "nacl-001-structure")
        self.assertEqual(linked["p14ReportSha256"], visual.digest(p14.read_bytes()))
        report = visual.run(self.cases, None, self.out, p14_report=p14)
        self.assertEqual(report["vestaGuiStatus"], "NOT_RUN",
                         "P14 evidence cannot substitute for V15 raster captures")
        document["vestaGuiExecuted"] = False
        p14.write_text(json.dumps(document))
        with self.assertRaisesRegex(ValueError, "P14 must"):
            visual.link_p14_report(p14, self.cases)

    def test_tampered_source_pin_rejected(self):
        bad = deepcopy(self.cases)
        bad[0]["sourceGitBlobSha1"] = "0" * 40
        manifest = self.root / "bad-pins.json"
        manifest.write_text(json.dumps({"schema": "kristalyapi.vesta15.visual-cases.v1", "cases": bad}))
        with self.assertRaisesRegex(ValueError, "Git blob"):
            visual.pinned_cases(manifest)


if __name__ == "__main__":
    unittest.main()
