#!/usr/bin/env python3
"""Generate element-data.js: display radius sets and colour schemes.

Data come from the mendeleev package (MIT licence), which records the
original publications:
- van der Waals radii: S. Alvarez, Dalton Trans. 42 (2013) 8617.
- Effective ionic radii: R. D. Shannon, Acta Cryst. A32 (1976) 751.
- Jmol and CPK colours as distributed by mendeleev.

Usage: python3 tools/build_element_data.py
Requires mendeleev (pip install mendeleev).
"""
import json
import math
from pathlib import Path

from mendeleev import __version__ as mendeleev_version
from mendeleev.fetch import fetch_table


def clean(value):
    return None if value is None or (isinstance(value, float) and math.isnan(value)) else value


def main():
    elements = fetch_table('elements').set_index('atomic_number')
    ions = fetch_table('ionicradii')
    vdw, jmol, cpk = {}, {}, {}
    for _, row in elements.iterrows():
        symbol = row['symbol']
        radius = clean(row['vdw_radius_alvarez'])
        if radius:
            vdw[symbol] = round(radius / 100, 3)
        for target, column in ((jmol, 'jmol_color'), (cpk, 'cpk_color')):
            colour = clean(row[column])
            if isinstance(colour, str) and len(colour) == 7 and colour.startswith('#'):
                target[symbol] = colour.lower()
    # Shannon effective ionic radii (Å): symbol → charge → coordination → spin → radius.
    shannon = {}
    for _, row in ions.iterrows():
        radius = clean(row['ionic_radius'])
        if radius is None:
            continue
        symbol = elements.loc[int(row['atomic_number']), 'symbol']
        spin = clean(row['spin']) or ''
        shannon.setdefault(symbol, {}).setdefault(str(int(row['charge'])), {}) \
            .setdefault(str(row['coordination']).strip(), {})[spin] = round(radius / 100, 4)
    data = {
        'source': {
            'vdw': 'S. Alvarez, Dalton Trans. 42 (2013) 8617-8636',
            'ionic': 'R. D. Shannon, Acta Cryst. A32 (1976) 751-767 (effective ionic radii)',
            'colours': 'Jmol and CPK colour tables',
            'via': 'mendeleev ' + mendeleev_version,
        },
        'vdw': vdw, 'shannon': shannon, 'jmol': jmol, 'cpk': cpk,
    }
    header = ('/* Generated by tools/build_element_data.py; do not edit by hand.\n'
              ' * Display radius sets and colour schemes with their sources (see SOURCE). */\n')
    body = 'export const ELEMENT_DATA=' + json.dumps(data, ensure_ascii=False, separators=(',', ':'), sort_keys=True) + ';\n'
    Path(__file__).resolve().parent.parent.joinpath('element-data.js').write_text(header + body, encoding='utf-8')


if __name__ == '__main__':
    main()
