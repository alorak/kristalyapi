#!/usr/bin/env python3
"""Generate export-glyphs.js: glyph outlines used to write text as vector paths.

Vector exports (SVG, PDF, EPS) draw labels as filled outlines instead of
referencing a font, so journal preflight checks find no missing or unembedded
fonts and the figure looks the same on every system.

Source fonts: Liberation Sans Regular and Bold (SIL Open Font License 1.1,
metric-compatible with Helvetica/Arial). Only the outlines of the characters
below are kept. The OFL text is in licenses/OFL-1.1.txt.

Usage: python3 tools/build_export_glyphs.py [font-directory]
Requires fontTools (pip install fonttools).
"""
import json
import sys
from pathlib import Path

from fontTools.pens.basePen import BasePen
from fontTools.ttLib import TTFont

CHARS = ''.join(chr(c) for c in range(32, 127)) + 'Åαβγ°·−'
FONTS = {'regular': 'LiberationSans-Regular.ttf', 'bold': 'LiberationSans-Bold.ttf'}


class PathPen(BasePen):
    """Records a glyph as M/L/C/Z commands in font units, y up.

    BasePen turns TrueType quadratic segments into exact cubic curves, which
    PDF and PostScript require."""

    def __init__(self, glyph_set):
        super().__init__(glyph_set)
        self.parts = []

    def _point(self, pt):
        return '%d %d' % (round(pt[0]), round(pt[1]))

    def _moveTo(self, pt):
        self.parts.append('M' + self._point(pt))

    def _lineTo(self, pt):
        self.parts.append('L' + self._point(pt))

    def _curveToOne(self, p1, p2, p3):
        self.parts.append('C' + ' '.join(self._point(p) for p in (p1, p2, p3)))

    def _closePath(self):
        self.parts.append('Z')


def font_data(path):
    font = TTFont(path)
    cmap, glyph_set = font.getBestCmap(), font.getGlyphSet()
    metrics = font['hmtx'].metrics
    glyphs = {}
    for char in CHARS:
        name = cmap.get(ord(char))
        if name is None:
            raise SystemExit('missing glyph %r in %s' % (char, path))
        pen = PathPen(glyph_set)
        glyph_set[name].draw(pen)
        glyphs[char] = [metrics[name][0], ''.join(pen.parts)]
    return {'unitsPerEm': font['head'].unitsPerEm, 'capHeight': font['OS/2'].sCapHeight, 'glyphs': glyphs}


def main():
    directory = Path(sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/truetype/liberation')
    data = {style: font_data(directory / name) for style, name in FONTS.items()}
    header = ('/* Generated by tools/build_export_glyphs.py; do not edit by hand.\n'
              ' * Glyph outlines from Liberation Sans Regular and Bold.\n'
              ' * Digitized data copyright (c) 2010 Google Corporation.\n'
              ' * Copyright (c) 2012 Red Hat, Inc.\n'
              ' * Licensed under the SIL Open Font License 1.1 (licenses/OFL-1.1.txt).\n'
              ' * Outlines are in font units with y pointing up. */\n')
    body = 'export const EXPORT_GLYPHS=' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n'
    Path(__file__).resolve().parent.parent.joinpath('export-glyphs.js').write_text(header + body, encoding='utf-8')


if __name__ == '__main__':
    main()
